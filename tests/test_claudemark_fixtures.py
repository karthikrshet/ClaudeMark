def test_watermarked_text_forensics(tmp_path):
    txt_file = tmp_path / "watermarked.txt"
    txt_file.write_text(
        "Confidential\u200b manuscript\u200c payload\ufeff test\u00a0here.",
        encoding="utf-8",
    )

    rep = analyze_unicode_forensics(txt_file.read_text(encoding="utf-8"))
    assert rep.total_anomalies >= 4
    assert rep.has_anomalies
    assert rep.zero_width_count >= 3
    assert rep.nbsp_count == 1


def test_stylometry_detectors_discrimination():
    ai_sample = (
        "In conclusion, it is important to analyze comprehensive paradigms across various stakeholders. "
        "Furthermore, modern frameworks ensure seamless integration and optimal efficiency across all organizational workflows. "
        "Therefore, strategic alignment remains vital for long-term sustainability."
    )
    hum_sample = (
        "We took the backroads through the hills yesterday. It rained most of the morning, "
        "so the trails were soaked and slick with mud. By afternoon though, the sun came out "
        "and we stopped at an old wooden bridge to rest."
    )

    det = detector_registry.get("claude")
    res_ai = det.detect(ai_sample)
    res_hum = det.detect(hum_sample)

    assert 0.0 <= res_ai.signal_score <= 1.0
    assert 0.0 <= res_hum.signal_score <= 1.0
