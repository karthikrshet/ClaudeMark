"""Integration tests for multi-format file inspection, cleaning, and text forensics."""

from pathlib import Path
import pytest

from claudemark.core.unicode_forensics import analyze_unicode_forensics
from claudemark.detectors.registry import detector_registry
from claudemark.provenance.batch import clean_single_file, inspect_single_file


def test_html_document_inspection_and_cleaning(tmp_path):
    html_file = tmp_path / "sample_ai.html"
    html_file.write_text(
        '<!DOCTYPE html><html><head><meta name="generator" content="ChatGPT">'
        '<meta name="ai-model" content="Claude-3.5-Sonnet"></head>'
        '<body><p>Hello\u200B world with AI provenance markers.</p></body></html>',
        encoding="utf-8",
    )

    rep = inspect_single_file(html_file)
    assert rep.file_format in ("html", "htm")
    assert rep.suspicious
    assert rep.has_ai_metadata

    cleaned_out = tmp_path / "cleaned.html"
    clean_rep = clean_single_file(html_file, cleaned_out)
    assert clean_rep.success
    assert cleaned_out.is_file()
    clean_text = cleaned_out.read_text(encoding="utf-8")
    assert "generator" not in clean_text
    assert "\u200b" not in clean_text


